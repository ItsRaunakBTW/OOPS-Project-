// =============================================================================
// Operator<< overload – stream insertion
// Declared as `friend` in the header so it can access private members.
// Allows: std::cout << station;
// =============================================================================
std::ostream& operator<<(std::ostream& os, const SensorStation& s) {
    os << std::fixed << std::setprecision(2);
    os << "[Station " << s.stationId << " | " << s.regionName << "] "
       << "Rainfall=" << s.rainfallRate << "mm/hr "
       << "Slope=" << s.slopeAngle << "deg "
       << "Soil=" << s.soilMoisture << "% "
       << "Vib=" << s.vibrationFreq << "Hz "
       << "River=" << s.riverWaterLevel << "m "
       << "HazardIdx=" << s.hazardIndex
       << " (" << classifyRisk(s.hazardIndex) << ")";
    return os;
}

