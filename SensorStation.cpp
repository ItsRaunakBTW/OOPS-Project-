// TelemetryAuditor::auditStation
// Because TelemetryAuditor is declared as a `friend class` inside
// SensorStation, this method can access stationId, rainfallRate,
// vibrationFreq, and soilMoisture DIRECTLY — no getters required.
// This demonstrates the friend-class mechanism: the auditor acts as a trusted
// diagnostic tool with privileged internal access.
// =============================================================================
void TelemetryAuditor::auditStation(const SensorStation& s) {
    std::cout << std::fixed << std::setprecision(3);
    std::cout << "╔══════════════════════════════════════════════╗\n";
    std::cout << "║         TELEMETRY AUDIT REPORT               ║\n";
    std::cout << "╠══════════════════════════════════════════════╣\n";
    // Direct private-member access (permitted because TelemetryAuditor is friend)
    std::cout << "║  Station ID     : " << s.stationId       << "\n";
    std::cout << "║  Rainfall Rate  : " << s.rainfallRate    << " mm/hr\n";
    std::cout << "║  Vibration Freq : " << s.vibrationFreq   << " Hz\n";
    std::cout << "║  Soil Moisture  : " << s.soilMoisture    << " %\n";
    // Classify based on the computed hazard index
    std::cout << "║  Risk Level     : " << classifyRisk(s.hazardIndex) << "\n";
    std::cout << "╚══════════════════════════════════════════════╝\n";
}

