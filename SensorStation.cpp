// =============================================================================
// Operator> overload – comparison by hazardIndex
// Allows: if (stationA > stationB) { ... }
// Returns true if *this is MORE hazardous than other.
// =============================================================================
bool SensorStation::operator>(const SensorStation& other) const {
    return hazardIndex > other.hazardIndex;
}

// =============================================================================
// computeHazardIndex – Overload 1: Landslide Risk
// Parameters: rainfallRate (mm/hr), slopeAngle (degrees)
// Formula: (rainfallRate/200 * 50) + (slopeAngle/90 * 50), capped at 100
// =============================================================================
float computeHazardIndex(float rainfallRate, float slopeAngle) {
    float index = (rainfallRate / 200.0f * 50.0f) +
                  (slopeAngle   /  90.0f * 50.0f);
    return std::min(index, 100.0f);
}

// =============================================================================
// computeHazardIndex – Overload 2: Seismic / Soil Saturation Risk
// Parameters: soilSaturation (0–100%), vibrationFrequency (Hz), SeismicTag{}
// The SeismicTag parameter is a zero-cost tag-dispatch idiom to disambiguate
// this overload from Overload 1 at compile time (both would otherwise share
// the identical (float, float) signature).
// Formula: (soilSaturation/100 * 60) + (vibrationFrequency/20 * 40), cap 100
// =============================================================================
float computeHazardIndex(float soilSaturation, float vibrationFrequency,
                         SeismicTag /*tag*/) {
    float index = (soilSaturation    / 100.0f * 60.0f) +
                  (vibrationFrequency /  20.0f * 40.0f);
    return std::min(index, 100.0f);
}

// =============================================================================
// computeHazardIndex – Overload 3: Flash-Flood Risk
// Parameters: riverLevel (m), rainfallRate (mm/hr), slopeAngle (degrees)
// Formula: (riverLevel/15*50) + (rainfallRate/200*30) + (slopeAngle/90*20)
// =============================================================================
float computeHazardIndex(float riverLevel, float rainfallRate, float slopeAngle) {
    float index = (riverLevel    /  15.0f * 50.0f) +
                  (rainfallRate  / 200.0f * 30.0f) +
                  (slopeAngle    /  90.0f * 20.0f);
    return std::min(index, 100.0f);
}

